/** The locale this browser speaks, decided once per page load. */
export function currentLocale(): Locale {
  if (typeof navigator === 'undefined') return 'en'
  return navigator.language.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}

/** Replace the {name} placeholders with the supplied values. */
function interpolate(text: string, vars?: Readonly<Record<string, string | number>>): string {
  if (vars === undefined) return text
  return text.replace(/\{(\w+)\}/g, (whole, name: string) => {
    const value = vars[name]
    return value === undefined ? whole : String(value)
  })
}

/**
 * Translate one key.
 *
 * A missing key falls back to the key itself rather than throwing: a settings
 * page that loses one label is still usable, while a throw blanks the page.
 */
export function t(key: MessageKey, vars?: Readonly<Record<string, string | number>>): string {
  const dictionary: Record<MessageKey, string> = currentLocale() === 'zh' ? ZH : EN
  return interpolate(dictionary[key], vars)
}

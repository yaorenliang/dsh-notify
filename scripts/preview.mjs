#!/usr/bin/env node
/**
 * Boot a second Harness instance with this checkout loaded, on another port.
 *
 * Integration testing must never require restarting the instance you are using:
 * this overlay adds the plugin row next to the live profile's composition and
 * serves it on a throwaway port instead.
 *
 * Usage: pnpm preview [--port 3099]
 */
import { spawn } from 'node:child_process'
import { mkdtempSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { join, resolve } from 'node:path'

const portFlag = process.argv.indexOf('--port')
const port = portFlag === -1 ? '3099' : process.argv[portFlag + 1] ?? '3099'
const root = resolve(import.meta.dirname, '..')
const dir = mkdtempSync(join(tmpdir(), 'dsh-notify-preview-'))
const patch = join(dir, 'cordis.patch.yml')

writeFileSync(patch, [
  '# Generated by scripts/preview.mjs — not part of the repository.',
  '- insert:',
  '    - id: dsh-notify-preview',
  `      name: '${root}'`,
  '',
].join('\n'), 'utf8')

console.log(`[dsh-notify] preview overlay: ${patch}`)
console.log(`[dsh-notify] serving http://127.0.0.1:${port} (the live instance is untouched)`)

const child = spawn('dsh', ['web', '--port', port, '--no-open', '--patch', patch], {
  stdio: 'inherit',
  env: process.env,
})
child.on('exit', (code) => process.exit(code ?? 0))
